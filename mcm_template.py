import pandas as pd
import matplotlib.pyplot as plt

# ------------------------------------------------------------
# 【第1处要改 🔴】csv文件名（改成比赛下载的文件名，必须一字不差）
# ------------------------------------------------------------
df = pd.read_csv("Problem_C_Data.csv")

# ====================== 查看数据（不需要改） ======================
print("===== 原始数据 =====")
print(df)

# 超级重要：先看列名，防止后面 KeyError 报错
print("\n===== 所有列名 =====")
print(df.columns)

# 基础统计：均值、最大、最小、标准差
print("\n===== 基础统计信息 =====")
print(df.describe())

# 检查缺失值：每一列有多少个空单元格
print("\n===== 缺失值数量 =====")
print(df.isnull().sum())

# ====================== 缺失值处理（不需要改） ======================
# 复制一份表格，保护原始数据不被改动
df_fill = df.copy()

# ------------------------------------------------------------
# 【第2处要改 🔴】列名：把 "数值" 替换成你csv里的真实列名
#               有多个列需要填充就写多行，填哪种值可自选
# ------------------------------------------------------------
df_fill["数值"] = df_fill["数值"].fillna(df_fill["数值"].mean())

print("\n===== 填充缺失值后的数据 =====")
print(df_fill)

# ====================== 数据筛选 ======================
# ------------------------------------------------------------
# 【第3处要改 🔴】筛选条件：列名、比较符号（> < >= <=）、阈值数字
# ------------------------------------------------------------
res = df_fill[ df_fill["数值"] > 20 ]
print("\n===== 筛选后的数据 =====")
print(res)

# 统计筛选后数据的平均值
print("\n筛选后数据平均值：", res["数值"].mean())

# ====================== 画图 ======================
# ------------------------------------------------------------
# 【第4处要改 🔴】绘图：坐标轴列名、英文标签、标题、图片文件名
# ------------------------------------------------------------
plt.plot(df_fill["序号"], df_fill["数值"])
plt.xlabel("Index")
plt.ylabel("Value")
plt.title("Data Curve")
plt.savefig("result_plot.png")

print("\n✅ 运行完成，图片已保存为 result_plot.png")
